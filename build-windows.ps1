param(
    [string]$Python = 'python',
    [string]$SearXNGBranch = 'master'
)

$ErrorActionPreference = 'Stop'
$PythonCommand = Get-Command $Python -ErrorAction SilentlyContinue
if (-not $PythonCommand) { throw "Python was not found: $Python" }
$PythonExe = $PythonCommand.Source
$PythonInfo = & $PythonExe -c 'import platform,sys; print(sys.version_info.major,sys.version_info.minor,sys.version_info.micro,platform.architecture()[0])'
if ($LASTEXITCODE -ne 0 -or $PythonInfo -notmatch '^3 (11|12) \d+ 64bit$') {
    throw "Build KittySearch with 64-bit Python 3.11 or 3.12 so SearXNG can be bundled. Found: $PythonInfo"
}
$Version = (& $PythonExe -c 'import platform; print(platform.python_version())').Trim()
$VersionParts = $Version.Split('.')
$VersionTag = 'python' + $VersionParts[0] + $VersionParts[1]
$BuildRoot = Join-Path $PSScriptRoot 'build'
$BundleRoot = Join-Path $BuildRoot 'searxng-runtime'
$Source = Join-Path $BundleRoot 'source'
$PythonRoot = Join-Path $BundleRoot 'python'
$PackageRoot = Join-Path $BundleRoot 'site-packages'
$Archive = Join-Path $BuildRoot 'searxng-source.zip'

if (Test-Path -LiteralPath $BundleRoot) { Remove-Item -LiteralPath $BundleRoot -Recurse -Force }
New-Item -ItemType Directory -Force -Path $BuildRoot, $BundleRoot, $PackageRoot | Out-Null

Write-Host "Downloading SearXNG source ($SearXNGBranch)..."
$SourceZip = Join-Path $BuildRoot 'searxng-upstream.zip'
Invoke-WebRequest -Uri "https://github.com/searxng/searxng/archive/refs/heads/$SearXNGBranch.zip" -OutFile $SourceZip -UseBasicParsing
& $PythonExe (Join-Path $PSScriptRoot 'extract-searxng-source.py') $SourceZip $Source
if ($LASTEXITCODE -ne 0) { throw 'SearXNG source extraction failed.' }
& $PythonExe (Join-Path $PSScriptRoot 'patch-searxng-windows.py') $Source
if ($LASTEXITCODE -ne 0) { throw 'SearXNG Windows compatibility patch failed.' }
$BranchLiteral = ConvertTo-Json -InputObject $SearXNGBranch -Compress
@"
# SPDX-License-Identifier: AGPL-3.0-or-later
# Generated by KittySearch's Windows build.
VERSION_STRING = "1.0.0+windows"
VERSION_TAG = "1.0.0"
DOCKER_TAG = "1.0.0-windows"
GIT_URL = "https://github.com/searxng/searxng"
GIT_BRANCH = $BranchLiteral
"@ | Set-Content -LiteralPath (Join-Path $Source 'searx\version_frozen.py') -Encoding UTF8

Write-Host 'Installing SearXNG dependencies for the embedded runtime...'
& $PythonExe -m pip install --upgrade pip
if ($LASTEXITCODE -ne 0) { throw 'Could not upgrade pip.' }
& $PythonExe -m pip install --target $PackageRoot -r (Join-Path $Source 'requirements.txt')
if ($LASTEXITCODE -ne 0) { throw 'Could not install SearXNG dependencies.' }

Write-Host "Downloading embeddable CPython $Version..."
$EmbeddedZip = Join-Path $BuildRoot 'python-embedded.zip'
Invoke-WebRequest -Uri "https://www.python.org/ftp/python/$Version/python-$Version-embed-amd64.zip" -OutFile $EmbeddedZip -UseBasicParsing
Expand-Archive -LiteralPath $EmbeddedZip -DestinationPath $PythonRoot -Force
$PthFile = Get-ChildItem -LiteralPath $PythonRoot -Filter "$VersionTag*._pth" | Select-Object -First 1
if (-not $PthFile) { throw 'The embeddable Python archive did not contain its import path file.' }
$PthText = @"
$VersionTag.zip
.
..\source
..\site-packages
import site
"@
[System.IO.File]::WriteAllText($PthFile.FullName, $PthText, [System.Text.UTF8Encoding]::new($false))

# SearXNG is licensed under AGPL-3.0-or-later. Ship its corresponding source
# beside the executable as well as embedding the runnable files in the EXE.
$Dist = Join-Path $PSScriptRoot 'dist'
New-Item -ItemType Directory -Force -Path $Dist | Out-Null
$SourceNotice = Join-Path $Source 'LICENSE'
if (-not (Test-Path -LiteralPath $SourceNotice)) { throw 'SearXNG source archive has no LICENSE file.' }
Compress-Archive -Path (Join-Path $Source '*') -DestinationPath (Join-Path $Dist 'SearXNG-source.zip') -Force

Write-Host 'Building the one-file KittySearch executable with SearXNG included...'
& $PythonExe -m pip install -r (Join-Path $PSScriptRoot 'requirements-build.txt')
if ($LASTEXITCODE -ne 0) { throw 'Could not install PyInstaller.' }
& $PythonExe -m PyInstaller --noconfirm --clean --onefile --name KittySearch --windowed --add-data "$BundleRoot;searxng-runtime" (Join-Path $PSScriptRoot 'kittysearch.py')
if ($LASTEXITCODE -ne 0) { throw 'PyInstaller failed.' }
Write-Host 'Portable executable created at dist\KittySearch.exe (SearXNG runtime is embedded).'
Write-Host 'Distribute dist\SearXNG-source.zip with the executable to provide the corresponding SearXNG source.'
